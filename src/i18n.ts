const messages = { zh, en }

type Values = Record<string, string | number>
export type Message = { key: MessageKey; values?: Values }
export type Translate = (message: MessageKey | Message, values?: Values) => string

export function createTranslator(language: Language): Translate {
  return (message, values = {}) => {
    const key = typeof message === 'string' ? message : message.key
    const parameters = typeof message === 'string' ? values : message.values
    return messages[language][key].replace(/\{(\w+)\}/g, (match, parameter: string) =>
      String(parameters?.[parameter] ?? match))
  }
}

const regionNames: Readonly<Record<string, string>> = {
  '嘉兴周边样例窗口': 'Jiaxing area sample window',
}

export function localisedRegionName(name: string, language: Language) {
  return language === 'en' ? (regionNames[name] ?? name) : name
}

const serverErrors: Readonly<Record<string, MessageKey>> = {
  '请选择互不重复的已登记物种。': 'invalidSpecies',
  '排除网格必须位于当前样例窗口，且编号不能重复。': 'invalidExclusions',
  '没有找到该图层。': 'layerNotFound',
  '网格在当前样例窗口之外。': 'cellOutside',
  '请先运行 pnpm build，或用 pnpm dev 启动前端。': 'frontendUnavailable',
}

export function requestFailure(cause: unknown): Message {
  if (!(cause instanceof RequestError)) return { key: 'requestFailed' }
  const key = Object.hasOwn(serverErrors, cause.message) ? serverErrors[cause.message] : undefined
  return key ? { key } : { key: 'httpFailure', values: { status: cause.status } }
}
